"""Build a safe synthetic demonstration case."""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from . import __version__
from .integrity import seal_case
from .tracegraph import build_trace_report


def _write_json(path: Path, data: object) -> None:
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def create_demo(output_dir: Path) -> Path:
    output_dir = output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    case_id = "SYNTHETIC-CASE-001"
    case: dict[str, Any] = {
        "case_id": case_id,
        "scope": "synthetic-demonstration-only",
        "authorization": {
            "status": "NOT_APPLICABLE_SYNTHETIC",
            "note": "This generated dataset contains no real communications and is not a valid investigative authorization.",
        },
        "reported_event_id": "evt-004",
        "requested_mode": "ORIGIN_ONLY",
        "source_identity_model": "synthetic pseudonymous actor IDs only",
        "created_by_tool_version": __version__,
    }
    events: list[dict[str, Any]] = [
        {
            "event_id": "evt-001", "event_type": "ORIGIN", "actor_id": "acct:synthetic-A",
            "timestamp": "2026-10-23T08:30:00Z", "time_source": "simulated-client-clock",
            "parent_event_id": None, "content_ref": "content:demo-001", "evidence_class": "synthetic",
        },
        {
            "event_id": "evt-002", "event_type": "FORWARD", "actor_id": "acct:synthetic-B",
            "timestamp": "2026-10-23T08:31:12Z", "time_source": "simulated-client-clock",
            "parent_event_id": "evt-001", "content_ref": "content:demo-001", "evidence_class": "synthetic",
        },
        {
            "event_id": "evt-003", "event_type": "FORWARD", "actor_id": "acct:synthetic-C",
            "timestamp": "2026-10-23T08:33:41Z", "time_source": "simulated-client-clock",
            "parent_event_id": "evt-002", "content_ref": "content:demo-001", "evidence_class": "synthetic",
        },
        {
            "event_id": "evt-004", "event_type": "REPORT", "actor_id": "acct:synthetic-D",
            "timestamp": "2026-10-23T08:40:09Z", "time_source": "simulated-client-clock",
            "parent_event_id": "evt-003", "content_ref": "content:demo-001", "evidence_class": "synthetic",
        },
        {
            "event_id": "evt-005", "event_type": "FORWARD", "actor_id": "acct:synthetic-E",
            "timestamp": "2026-10-23T08:35:10Z", "time_source": "simulated-client-clock",
            "parent_event_id": "evt-002", "content_ref": "content:demo-001", "evidence_class": "synthetic",
        },
        {
            "event_id": "evt-006", "event_type": "DELIVER", "actor_id": "acct:synthetic-F",
            "timestamp": "2026-10-23T08:36:05Z", "time_source": "simulated-client-clock",
            "parent_event_id": "evt-005", "content_ref": "content:demo-001", "evidence_class": "synthetic",
        },
    ]
    reported_id = str(case["reported_event_id"])
    report = build_trace_report(events, reported_id, "ORIGIN_ONLY")
    path_demo = build_trace_report(events, reported_id, "PATH")
    tree_demo = build_trace_report(events, reported_id, "TREE")
    _write_json(output_dir / "case.json", case)
    _write_json(output_dir / "events.json", events)
    _write_json(output_dir / "trace.json", report)
    _write_json(output_dir / "trace-path-demo.json", path_demo)
    _write_json(output_dir / "trace-tree-demo.json", tree_demo)
    report_md = """# Synthetic WhatsApp Traceability Research Lab demonstration report

> **Synthetic only.** No WhatsApp data, real person, phone number, or actual forwarding event is represented here.

## Default mode: first-originator only

- Pseudonymous actor: `acct:synthetic-A`
- Basis: the root `ORIGIN` event in the supplied synthetic graph.
- Status: `synthetic-only; not an identity claim`.
- Disclosure: only the origin candidate and origin event are included in `trace.json`; the path and tree are intentionally omitted.

## Separate synthetic research fixtures

- `trace-path-demo.json`: synthetic origin-to-reported-event path only.
- `trace-tree-demo.json`: synthetic full forwarding tree, including branches.

These fixtures exist to test that output scope changes with the requested mode. They are not mixed into the default origin-only report.

## Interpretation limits

This report is generated by traversing explicit parent pointers in synthetic input. It does not implement a cryptographic source-tracing construction, verify phone ownership, prove that a real person operated a device, or prove the truth of a message. The branch shown in the tree fixture is only a branch present in this supplied dataset. Timestamps are not trusted-time evidence.
"""
    (output_dir / "report.md").write_text(report_md, encoding="utf-8")
    seal_case(
        output_dir,
        case_id,
        [
            ("case.json", "case-metadata", "synthetic"),
            ("events.json", "source-events", "synthetic"),
            ("trace.json", "derived-origin-only-report", "synthetic-derived"),
            ("trace-path-demo.json", "derived-path-demo", "synthetic-derived"),
            ("trace-tree-demo.json", "derived-tree-demo", "synthetic-derived"),
            ("report.md", "human-readable-report", "synthetic-derived"),
        ],
    )
    return output_dir
